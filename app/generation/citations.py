"""Code-level citation validator for RAG generation.

Validates and prunes citations generated by LLM to ensure all references
strictly map to retrieved chunks, preventing citation hallucinations.
"""

from __future__ import annotations

import logging
from collections.abc import Sequence
from pathlib import Path

from app.generation.models import Citation
from app.retrieval.models import RetrievedChunk

logger = logging.getLogger(__name__)


def normalize_source_name(name: str) -> str:
    """Normalize file name by taking basename and stripping extensions/spaces."""
    p = Path(name.strip())
    return p.name.lower()


def find_matching_chunk(
    citation: Citation,
    chunks: Sequence[RetrievedChunk],
) -> RetrievedChunk | None:
    """Find a retrieved chunk that validates the citation.

    Criteria:
    1. Source file basename matches.
    2. Page (if provided) is within the chunk's page_start..page_end.
    3. Article (if provided) matches or is found in chunk text.
    """
    cit_file = normalize_source_name(citation.source_file)

    for chunk in chunks:
        chunk_file = normalize_source_name(chunk.source_file)
        if cit_file not in chunk_file and chunk_file not in cit_file:
            continue

        # If page is specified, verify it falls within the chunk's range
        if citation.page is not None:
            if not (chunk.page_start <= citation.page <= chunk.page_end):
                continue

        # If article is specified, check article or text
        if citation.article:
            cit_art = citation.article.lower().strip()
            chunk_art = (chunk.article or "").lower()
            if cit_art not in chunk_art and cit_art not in chunk.text.lower():
                continue

        # If a quote snippet is provided, check if it exists in chunk text
        if citation.quote:
            quote_clean = citation.quote.strip()[:200]
            # Strip extra whitespace for fuzzy substring matching
            words = quote_clean.split()
            if len(words) >= 4:
                snippet = " ".join(words[:6]).lower()
                if snippet not in chunk.text.lower():
                    continue

        return chunk

    return None


def validate_citations(
    raw_citations: Sequence[Citation | dict],
    retrieved_chunks: Sequence[RetrievedChunk],
) -> list[Citation]:
    """Validate a list of raw citations against retrieved chunks, dropping hallucinations.

    Returns:
        List of verified Citation instances.
    """
    if not retrieved_chunks:
        return []

    verified: list[Citation] = []
    seen: set[tuple[str, str | None, int | None]] = set()

    for item in raw_citations:
        if isinstance(item, dict):
            try:
                cit = Citation(**item)
            except Exception as e:
                logger.debug("Failed to parse citation dict (%s): %s", item, e)
                continue
        else:
            cit = item

        # Cap quote length to 200 characters
        if cit.quote and len(cit.quote) > 200:
            cit = Citation(
                source_file=cit.source_file,
                article=cit.article,
                page=cit.page,
                quote=cit.quote[:200] + "...",
            )

        match = find_matching_chunk(cit, retrieved_chunks)
        if match is None:
            logger.info(
                "Pruning ungrounded citation: file=%s article=%s page=%s",
                cit.source_file,
                cit.article,
                cit.page,
            )
            continue

        # Fill in missing article or page from the matched chunk
        resolved = Citation(
            source_file=Path(match.source_file).name,
            article=cit.article or match.article,
            page=cit.page or match.page_start,
            quote=cit.quote,
        )

        key = (resolved.source_file, resolved.article, resolved.page)
        if key not in seen:
            seen.add(key)
            verified.append(resolved)

    return verified


def format_citations_markdown(citations: Sequence[Citation]) -> str:
    """Format citations into a readable markdown footnote section."""
    if not citations:
        return ""

    lines = ["\n\n**Tài liệu trích dẫn:**"]
    for idx, c in enumerate(citations, 1):
        parts = [f"[{idx}] {c.source_file}"]
        if c.article:
            parts.append(c.article)
        if c.page:
            parts.append(f"Trang {c.page}")
        line = " – ".join(parts)
        if c.quote:
            line += f'\n    > "{c.quote}"'
        lines.append(line)

    return "\n".join(lines)
